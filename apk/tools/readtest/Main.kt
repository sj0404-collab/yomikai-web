import net.koma.reader.ReadEngine

fun main() {
    val e = ReadEngine()
    val R = ReadEngine.Rules(dir = "rtl")
    fun L(t: String, l: Double, top: Double, r: Double, b: Double) = ReadEngine.Line(t, l, top, r, b, 0.9)

    // Страница из скриншота 22:41: два облачка рядом и одно ниже.
    // Левое облачко: 4 строки, разбитые на два куска («ВЫСО-» + «ЧЕСТВО»).
    val story = listOf(
        L("УЖЕ ПОРА НА-", 0.14, 0.10, 0.42, 0.13),
        L("ЧИНАТЬ ВСТРЕЧУ,", 0.14, 0.14, 0.44, 0.17),
        L("ТАК ЧТО ЕЁ ВЫСО-", 0.14, 0.18, 0.45, 0.21),
        L("-ЧЕСТВО, ДОЛЖНО", 0.14, 0.22, 0.44, 0.25),
        L("БЫТЬ, ПРИБЫЛА.", 0.14, 0.26, 0.42, 0.29),
        // Правое облачко — выше по странице, но правее: в манге читается первым.
        L("НЕ УВЕРЕН,", 0.58, 0.22, 0.86, 0.25),
        L("КАК СТОИТ СКА-", 0.58, 0.26, 0.87, 0.29),
        L("ЗАТЬ ЭТО, НО...", 0.58, 0.30, 0.86, 0.33),
        // Нижнее облачко.
        L("В БУДУЩЕМ,", 0.14, 0.62, 0.44, 0.65),
        L("КОГДА ВЫ БУДЕ-", 0.14, 0.66, 0.45, 0.69),
        L("ТЕ ГОВОРИТЬ С ЕЁ", 0.14, 0.70, 0.47, 0.73),
        L("ВЫСОЧЕСТВОМ.", 0.14, 0.74, 0.45, 0.77),
    )
    val plan = e.plan(story, R)
    println("реплик: ${plan.size}")
    plan.forEachIndexed { i, o -> println("  ${i + 1}. ${o.optString("text")}") }

    // Полосы: страница 4000 px, экран 1000 px.
    println("полос (4000/1000): " + e.bands(4000.0, 1000.0, R).length())
    println("полос (страница по экрану): " + e.bands(800.0, 1000.0, R).length())
}
